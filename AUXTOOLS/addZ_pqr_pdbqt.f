      SUBROUTINE UCASE (STRNG)                                          
C    ==========================                                         
C                                                                       
C"""""""""""""""""""""""""""""""""""""""""""""""""""""""""""""""""""""""
C     CONVERTS LOWER CASE CHARACTERS TO UPPER CASE                       
C                                                                       
      CHARACTER*(*) STRNG                                               
C                                                                       
C      write(7,'(A)') STRNG                                             
C                                                                       
      DO 10 I = 1,LEN(STRNG)                                            
         IF ( ( STRNG(I:I).GE. 'a' )  .AND.                             
     +        ( STRNG(I:I) .LE. 'z' ) )                                 
     +   STRNG(I:I) = CHAR(ICHAR(STRNG(I:I)) + ICHAR('A') - ICHAR('a')) 
 10   CONTINUE                                                          
      RETURN                                                            
      END                                                               
