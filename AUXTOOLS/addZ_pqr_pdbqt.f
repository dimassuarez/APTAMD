      SUBROUTINE RDPQR (IUNIT,NUMATM,NUMRES,NZATM,NFA,NLA,TA,RESNAM,
     &                  IDATM,IDRES,IDZATM,XR,YR,ZR,Q,RAD)
C     =============================================================
C
C"""""""""""""""""""""""""""""""""""""""""""""""""""""""""""""""""""""""
      implicit real  (a-h,o-z)
      parameter(maxatm=500000,maxres=200000)
C
C     All cards  ATOM or HETATM in IUNIT are
C     read to fill the coordinates and data for the protein
C
C     NOTE THAT THIS ROUTINE ASSUMES THAT BIG PDB FILES
C     ARE WELL WRITTEN, THAT IS, THAT RESIDUE NUMBER
C     IS WRITTEN WITH FORMAT I5
C
      integer iunit, numatm, numres
      dimension xr(*),yr(*),zr(*)
      dimension q(*),rad(*)
      dimension nfa(*),nla(*),idres(*),idatm(*)
      dimension idzatm(*)
      dimension indx(100),rx(100)
      character*4 ta(*)
      character*3 resnam(*) 
      character*80 line
C
      character head*4,tdum*3
C
      numatm=0
      numres=0
      iat=0
      ires=0
      idum0=0
      jres=0
      nzatm=0
C
      rewind(iunit)
 10   read(iunit,'(A4)',end=20,err=666) head
C
      IF ( head .eq. 'ZATM' ) THEN
          backspace(iunit)
          read(iunit,'(A80)') line
          CALL RDLINEA(line,indx,ni,rx,nr,nx,1)
          DO I=1,NI
             idzatm(NZATM+I)=indx(I)
          ENDDO
          NZATM=NZATM+NI

      ELSEIF (( head .eq. 'ATOM') .OR. 
     +         ( head .eq. 'HETA'))  THEN 

          backspace(iunit)
          iat=iat+1
          IF ( iat .gt. maxatm ) THEN 
               WRITE(6,'(''Reading Unit'',I3)') IUNIT  
               READ (IUNIT,'(A)') line
               WRITE(6,'(''Last line:'',/,A)') line   
               WRITE(6,'(''MAXATM='',I6)') maxatm 
               STOP '*** Too many atoms in PDB'
          ENDIF 
          read(iunit,'(6X,I5,1X,A4,1X,A3,1X,I5,4X,3F8.3,2F8.4)'
     &    ,err=666,end=666)
     & jat,ta(iat),tdum,jres,xr(iat),yr(iat),zr(iat),q(iat),rad(iat)
          Idatm(iat)=jat
          IF ( idum0 .ne. jres) THEN
            ires=ires+1
            nfa(ires)=iat
            resnam(ires)=tdum
            idres(ires)=jres
            idum0=jres
          ENDIF
C
      ENDIF
C
      GOTO 10
C
 20   CONTINUE
C
      numatm=iat
      numres=ires
      DO ires=1,numres-1
        nla(ires)=nfa(ires+1)-1
      ENDDO
      nla(numres)=numatm
C
      IF (NUMATM .eq. 0) THEN 
        WRITE(6,*) 'Zero Atoms in PDB file UNIT= ',Iunit
        STOP
      ENDIF
C
      RETURN
C
 666  WRITE(6,*) 'PROBLEMS READING PDB FILE IN UNIT=', Iunit
      STOP
      END
